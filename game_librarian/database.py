"""Database connections: the local SQLite file, or PostgreSQL for the hosted site, behind one interface.

All SQL stays in store.py, written once in SQL that both databases accept. This module hides what that SQL cannot:

* placeholders: store.py writes SQLite's ``?``; a PostgreSQL connection sends them as psycopg's ``%s``;
* rows: both kinds of connection return rows read by name or position (``row["name"]``, ``row[0]``), with
  ``keys()`` and ``dict(row)``;
* transactions: ``with conn:`` commits the statements inside it, or rolls all of them back on an error, as sqlite3
  does; a statement outside such a block is committed on its own;
* numbers: PostgreSQL's NUMERIC (a SUM over integers) comes back as an int when it is whole, else as a float, like
  SQLite's results;
* the schema: store.SCHEMA is SQLite's; postgres_statements() gives the same tables with PostgreSQL's types, and
  every text column compares and sorts byte by byte (COLLATE "C"), as SQLite does;
* connection rules: TLS that checks the server's certificate and host name (sslmode=verify-full) for any server but
  this computer, a small connection pool for the website, and a lock that keeps two refreshes from overlapping.

The connection URL (GAME_LIBRARIAN_DATABASE_URL) names the server, database and user. The password comes from the
PGPASSWORD environment variable (or a libpq password file), so it never has to be part of a setting that is shown.
Nothing here prints or logs a connection URL or a password.
"""

from __future__ import annotations

import os
import re
import sqlite3
import sys
import threading
from contextlib import contextmanager
from dataclasses import dataclass, field
from functools import lru_cache
from pathlib import Path
from typing import Any, Callable, Iterable, Iterator, Sequence

# Servers on this computer, where TLS is optional (a development database); any other server needs verify-full.
LOCAL_HOSTS = {"localhost", "127.0.0.1", "::1"}
VERIFY_FULL = "verify-full"
# libpq settings that apply unless the connection URL sets its own: give up on an unreachable server after 10 s,
# name the app in pg_stat_activity, and keep an idle connection (the refresh lock's, the pool's) from being dropped
# silently by a network device on the way.
CONNECTION_DEFAULTS = {"connect_timeout": "10", "application_name": "game-librarian", "keepalives": "1",
                       "keepalives_idle": "60", "keepalives_interval": "10", "keepalives_count": "6"}
POOL_MAX_SIZE = 4  # connections the website keeps for its page requests; a Burstable server allows about 50
POOL_TIMEOUT_SECONDS = 15  # how long a page request waits for a free connection before it fails
POOL_MAX_IDLE_SECONDS = 300  # an unused connection is closed after this long
# The number of the PostgreSQL advisory lock that the refreshing commands hold (any fixed 64-bit number works).
REFRESH_LOCK_KEY = 7_165_413_582_204_791_301

# The parts of store.py's SQL that differ between SQLite's and psycopg's parameter styles: a string literal ('it''s'),
# a quoted name ("x"), a comment (-- to the end of the line), a ? placeholder or a % sign.
SQL_TOKENS = re.compile(r"'(?:[^']|'')*'|\"(?:[^\"]|\"\")*\"|--[^\n]*|\?|%")
SQL_COMMENT = re.compile(r"--[^\n]*")
# SQLite type names in store.SCHEMA and PostgreSQL's equivalents, applied in this order. AUTOINCREMENT ids become
# identity columns that still accept the ids copied from SQLite (BY DEFAULT). INTEGER becomes BIGINT, since SQLite's
# integers have 64 bits; REAL is SQLite's 8-byte float; COLLATE "C" makes text compare by bytes, as in SQLite.
POSTGRES_TYPES = (
    (re.compile(r"\bINTEGER PRIMARY KEY AUTOINCREMENT\b"), "BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY"),
    (re.compile(r"\bINTEGER\b"), "BIGINT"),
    (re.compile(r"\bREAL\b"), "DOUBLE PRECISION"),
    (re.compile(r"\bTEXT\b"), 'TEXT COLLATE "C"'),
)
# A PostgreSQL role or schema name that can be quoted safely: letters, digits, _ and $, at most 63 characters.
SQL_NAME = re.compile(r"[A-Za-z_][A-Za-z0-9_$]{0,62}")


class DatabaseConfigError(ValueError):
    """A database setting that cannot be used. The message names the setting and never contains a password."""


@dataclass(frozen=True)
class PostgresDatabase:
    """The hosted catalog's PostgreSQL database: a libpq connection URL or key=value string.

    repr() leaves the URL out, because a URL may hold a password; describe() names the server without one.
    """

    url: str = field(repr=False)

    def parameters(self) -> dict[str, str]:
        """The libpq connection parameters with this app's rules applied.

        TLS: any server but this computer must be reached with sslmode=verify-full, which checks that the server's
        certificate comes from a trusted authority and names the host connected to. Without a root certificate
        setting (sslrootcert in the URL, or PGSSLROOTCERT), the trusted authorities are Mozilla's list as packaged by
        certifi, which includes both roots Azure Database for PostgreSQL uses (DigiCert Global Root G2 and Microsoft
        RSA Root Certificate Authority 2017), on Windows as well as in the Linux container.
        """
        params = _parse(self.url)
        host = params.get("host") or os.environ.get("PGHOST", "")
        if not host:
            raise DatabaseConfigError("GAME_LIBRARIAN_DATABASE_URL names no server (host).")
        local = all(part in LOCAL_HOSTS or part.startswith("/") for part in host.split(","))
        sslmode = params.get("sslmode") or os.environ.get("PGSSLMODE") or ("prefer" if local else VERIFY_FULL)
        if not local and sslmode != VERIFY_FULL:
            raise DatabaseConfigError(
                f"GAME_LIBRARIAN_DATABASE_URL (or PGSSLMODE) asks for sslmode={sslmode}, which does not check both the "
                "server's certificate and its host name. Use sslmode=verify-full, the default.")
        params["sslmode"] = sslmode
        has_roots = params.get("sslrootcert") or os.environ.get("PGSSLROOTCERT")
        if sslmode in ("verify-full", "verify-ca") and not has_roots:
            import certifi  # Mozilla's root certificates, also used by httpx for the source APIs

            params["sslrootcert"] = certifi.where()
        return {**CONNECTION_DEFAULTS, **params}

    def describe(self) -> str:
        """The database, server and user, never the password: 'PostgreSQL game_librarian on host:5432 as gl_app'."""
        params = _parse(self.url)
        user = params.get("user") or os.environ.get("PGUSER") or "(PGUSER)"
        host = params.get("host") or os.environ.get("PGHOST") or "(PGHOST)"
        port = params.get("port") or os.environ.get("PGPORT") or "5432"
        name = params.get("dbname") or os.environ.get("PGDATABASE") or user
        return f"PostgreSQL {name} on {host}:{port} as {user}"


def _parse(url: str) -> dict[str, str]:
    """The parameters of a connection URL or key=value string. A malformed one is reported without its text."""
    from psycopg import ProgrammingError
    from psycopg.conninfo import conninfo_to_dict

    try:
        return {key: str(value) for key, value in conninfo_to_dict(url).items() if value is not None}
    except ProgrammingError:  # psycopg's message quotes the string, which may contain a password
        raise DatabaseConfigError("GAME_LIBRARIAN_DATABASE_URL is not a valid PostgreSQL connection URL, such as "
                                  "postgresql://gl_app@myserver.postgres.database.azure.com/game_librarian") from None


# ---------------------------------------------------------------------- rows and connections


class Row(tuple):
    """A result row like sqlite3.Row: by position (row[0]) or by column name (row["name"]), with keys() and dict(row).

    As in sqlite3.Row, a name used twice in one result means its first column, and an unknown name raises IndexError.
    """

    def __new__(cls, index: dict[str, int], values: Iterable[Any]) -> Row:
        row = super().__new__(cls, values)
        row._index = index  # column name -> position, shared by the rows of one result
        return row

    def __getitem__(self, key):
        if isinstance(key, str):
            try:
                return tuple.__getitem__(self, self._index[key])
            except KeyError:
                raise IndexError("No item with that key") from None
        return tuple.__getitem__(self, key)

    def keys(self) -> list[str]:
        return list(self._index)


def _row_factory(cursor) -> Callable[[Any], Row]:
    """psycopg's row factory for Row: the column names come from the result's description."""
    index: dict[str, int] = {}
    for position, column in enumerate(cursor.description or ()):
        index.setdefault(column.name, position)
    return lambda values: Row(index, values)


@lru_cache(maxsize=4096)
def to_pyformat(sql: str) -> str:
    """SQLite-style SQL for psycopg: each ? placeholder becomes %s, and every % sign is doubled.

    A ? inside a string literal, a quoted name or a comment stays as it is. A % is doubled everywhere, because psycopg
    reads % signs in the whole statement. Example: "WHERE name LIKE '50%' AND id = ?" -> "... LIKE '50%%' AND id = %s".
    """
    def replace(match: re.Match) -> str:
        token = match.group()
        return "%s" if token == "?" else token.replace("%", "%%")

    return SQL_TOKENS.sub(replace, sql)


def _values(parameters) -> list:
    """The parameters as psycopg sends them. A bool becomes 0 or 1, as sqlite3 stores it: the schema has no boolean
    column, and PostgreSQL would refuse a boolean for an integer one."""
    if isinstance(parameters, dict):
        raise TypeError("store.py uses ? placeholders; named parameters are not supported")
    return [int(value) if isinstance(value, bool) else value for value in parameters]


class SQLiteConnection(sqlite3.Connection):
    """sqlite3's own connection, marked with its backend so that store.py can choose the few statements that differ."""

    backend = "sqlite"


class PostgresConnection:
    """A psycopg connection that store.py uses as it uses a sqlite3 one (see the module docstring).

    The psycopg connection runs in autocommit mode, so a statement outside `with conn:` is committed at once and no
    transaction stays open between page requests; `with conn:` opens one transaction for the statements inside it
    (a nested block joins the outer one).
    """

    backend = "postgresql"

    def __init__(self, raw, release: Callable[[Any], None]) -> None:
        self._raw = raw  # a psycopg.Connection in autocommit mode, prepared by _prepare
        self._release = release  # closes it, or gives it back to the pool
        self._transaction = None
        self._depth = 0

    def execute(self, sql: str, parameters=()):
        """Run one statement and return its cursor (fetchone, fetchall, iteration, rowcount)."""
        cursor = self._raw.cursor()
        if parameters is None or len(parameters) == 0:
            cursor.execute(sql)  # without parameters psycopg sends the text unchanged
        else:
            cursor.execute(to_pyformat(sql), _values(parameters))
        return cursor

    def executemany(self, sql: str, seq_of_parameters):
        """Run one statement for each parameter set; psycopg pipelines them, so they share round trips."""
        rows = [_values(parameters) for parameters in seq_of_parameters]
        cursor = self._raw.cursor()
        if rows:
            cursor.executemany(to_pyformat(sql), rows)
        return cursor

    def __enter__(self) -> PostgresConnection:
        if self._depth == 0:
            self._transaction = self._raw.transaction()
            self._transaction.__enter__()
        self._depth += 1
        return self

    def __exit__(self, exc_type, exc, traceback) -> bool:
        self._depth -= 1
        if self._depth == 0:
            transaction, self._transaction = self._transaction, None
            transaction.__exit__(exc_type, exc, traceback)  # commits, or rolls back when the block raised
        return False

    def copy_rows(self, table: str, columns: tuple[str, ...], rows: Iterable[Sequence]) -> None:
        """Load rows into a table with PostgreSQL's COPY (migrate-to-postgres): far faster than INSERTs, with every
        value sent in PostgreSQL's own text format. `table` and `columns` come from store.SCHEMA, never from input."""
        cursor = self._raw.cursor()
        with cursor.copy(f"COPY {table} ({', '.join(columns)}) FROM STDIN") as copy:
            for row in rows:
                copy.write_row(_values(row))

    def commit(self) -> None:
        """Nothing to do: a statement outside `with conn:` is already committed, and the block commits its own."""

    def rollback(self) -> None:
        """Nothing to do outside `with conn:` (see commit); inside it, an exception rolls the block back."""

    def close(self) -> None:
        if self._raw is not None:
            raw, self._raw = self._raw, None
            self._release(raw)


Connection = SQLiteConnection | PostgresConnection
AnyRow = sqlite3.Row | Row
Target = Path | PostgresDatabase  # what Settings.database gives: the SQLite file, or the PostgreSQL database


@lru_cache(maxsize=1)
def _numeric_loader():
    """psycopg's loader for NUMERIC values, made on first use (SQLite users never import psycopg)."""
    from psycopg.adapt import Loader

    class NumericLoader(Loader):
        """A NUMERIC value as an int when it is whole, else a float, as SQLite returns a SUM or an AVG."""

        def load(self, data):
            text = bytes(data).decode()
            try:
                return int(text)
            except ValueError:
                return float(text)

    return NumericLoader


def _prepare(raw) -> None:
    """Give a new psycopg connection this module's rows and numbers (also the pool's configure step)."""
    raw.row_factory = _row_factory
    raw.adapters.register_loader("numeric", _numeric_loader())


def connect_sqlite(path: Path) -> SQLiteConnection:
    """Open the SQLite catalog file. Rows behave like dicts (`row["name"]`)."""
    conn = sqlite3.connect(path, factory=SQLiteConnection)
    conn.row_factory = sqlite3.Row
    conn.execute("PRAGMA foreign_keys = ON")
    conn.execute("PRAGMA busy_timeout = 5000")
    return conn


def connect_postgres(target: PostgresDatabase) -> PostgresConnection:
    """Open one PostgreSQL connection (closed by close()). Errors name the server and user, never the password."""
    import psycopg
    from psycopg.conninfo import make_conninfo

    raw = psycopg.connect(make_conninfo(**target.parameters()), autocommit=True)
    _prepare(raw)
    return PostgresConnection(raw, release=lambda connection: connection.close())


_pools: dict[str, Any] = {}
_pools_lock = threading.Lock()


def _pooled_postgres(target: PostgresDatabase) -> PostgresConnection:
    """A connection from the process's pool for `target` (made on first use); close() gives it back."""
    from psycopg.conninfo import make_conninfo
    from psycopg_pool import ConnectionPool

    conninfo = make_conninfo(**target.parameters())
    with _pools_lock:
        pool = _pools.get(conninfo)
        if pool is None:
            pool = ConnectionPool(conninfo, min_size=0, max_size=POOL_MAX_SIZE, kwargs={"autocommit": True},
                                  configure=_prepare, check=ConnectionPool.check_connection,
                                  timeout=POOL_TIMEOUT_SECONDS, max_idle=POOL_MAX_IDLE_SECONDS,
                                  name="game-librarian", open=True)
            _pools[conninfo] = pool
    return PostgresConnection(pool.getconn(), release=pool.putconn)


def connect(target: Target | str, *, pooled: bool = False) -> Connection:
    """Open the catalog: a SQLite file path, or a PostgresDatabase. `pooled` reuses PostgreSQL connections (the
    website); SQLite always opens its file, which is cheap."""
    if isinstance(target, PostgresDatabase):
        return _pooled_postgres(target) if pooled else connect_postgres(target)
    return connect_sqlite(Path(target))


def is_postgres_error(exc: BaseException) -> bool:
    """Whether `exc` is psycopg's error: a PostgreSQL connection or statement failed. psycopg is loaded only by a
    PostgreSQL connection, so with SQLite this is always False."""
    psycopg = sys.modules.get("psycopg")
    return psycopg is not None and isinstance(exc, psycopg.Error)


def close_pools() -> None:
    """Close every PostgreSQL pool of this process (the website's shutdown, and the tests)."""
    with _pools_lock:
        pools = list(_pools.values())
        _pools.clear()
    for pool in pools:
        pool.close()


@contextmanager
def refresh_lock(target: Target) -> Iterator[bool]:
    """Hold the lock that keeps two refreshing commands (such as two `sync` runs) from writing at the same time.

    Yields True while this process holds it, or False when another one does. On PostgreSQL it is an advisory lock of
    its own connection's session, so PostgreSQL releases it when that connection ends, even after a crash. A SQLite
    file has no such lock: on one computer, start one refresh at a time.
    """
    if not isinstance(target, PostgresDatabase):
        yield True
        return
    conn = connect_postgres(target)
    try:
        yield bool(conn.execute("SELECT pg_try_advisory_lock(?)", (REFRESH_LOCK_KEY,)).fetchone()[0])
    finally:
        conn.close()  # ends the session, which releases the lock


# ---------------------------------------------------------------------- schema


def postgres_type(sqlite_type: str) -> str:
    """One column type of store.py's SQLite schema in PostgreSQL's words: 'TEXT' -> 'TEXT COLLATE "C"'."""
    for pattern, replacement in POSTGRES_TYPES:
        sqlite_type = pattern.sub(replacement, sqlite_type)
    return sqlite_type


def postgres_statements(sqlite_schema: str) -> list[str]:
    """store.py's SQLite schema as PostgreSQL statements: comments removed, types translated, one statement each."""
    text = postgres_type(SQL_COMMENT.sub("", sqlite_schema))
    return [statement.strip() for statement in text.split(";") if statement.strip()]


def quoted_name(name: str) -> str:
    """A role or schema name for a GRANT statement, quoted; anything but a plain name is refused, never quoted."""
    if not SQL_NAME.fullmatch(name):
        raise DatabaseConfigError(f"{name!r} is not a plain PostgreSQL name (letters, digits and _, at most 63).")
    return f'"{name}"'
