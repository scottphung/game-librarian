@needs_postgres
def test_postgresql_transactions_numbers_and_byte_order(settings):
    conn = store.connect(settings.database)
    try:
        assert conn.backend == "postgresql"
        with pytest.raises(RuntimeError):
            with conn:  # an error inside the block rolls back every statement of the block
                conn.execute("INSERT INTO sync_state (key, value) VALUES (?, ?)", ("a", "1"))
                raise RuntimeError("stop")
        assert store.get_state(conn, "a") is None
        store.set_state(conn, "a", "2")  # committed on its own
        assert store.get_state(conn, "a") == "2"
        conn.executemany("INSERT INTO sync_state (key, value) VALUES (?, ?)", [("B", "x"), ("a2", "x"), ("é", "x")])
        assert [row["key"] for row in conn.execute("SELECT key FROM sync_state ORDER BY key")] == \
            ["B", "a", "a2", "é"]  # byte order, as SQLite sorts, whatever the server's default collation
        row = conn.execute("SELECT COUNT(*) AS n, SUM(LENGTH(value)) AS total, AVG(LENGTH(value)) AS mean "
                           "FROM sync_state").fetchone()
        assert (row["n"], row["total"], row["mean"]) == (4, 4, 1.0)
        assert isinstance(row["total"], int) and isinstance(row["mean"], float)
    finally:
        conn.close()


@needs_postgres
def test_the_refresh_lock_lets_one_refresh_run_at_a_time(settings):
    with database.refresh_lock(settings.database) as first:
        with database.refresh_lock(settings.database) as second:
            assert first and not second
    with database.refresh_lock(settings.database) as again:
        assert again  # released when its connection ended


@needs_postgres
def test_the_runtime_only_checks_the_tables_and_says_how_to_create_them(settings):
    conn = store.connect(settings.database)
    try:
        assert store.missing_postgres_schema(conn) == []
        store.create_postgres_schema(conn)  # running it again keeps everything
        conn.execute("ALTER TABLE games DROP COLUMN screenshot_url")
        conn.execute("DROP TABLE wishlist_items")
        assert store.missing_postgres_schema(conn) == ["games.screenshot_url", "wishlist_items"]
    finally:
        conn.close()
    with pytest.raises(store.SchemaError, match="init-postgres"):
        store.initialize(settings.database)
    conn = store.connect(settings.database)
    try:
        store.create_postgres_schema(conn)  # adds the missing table and column back
        assert store.missing_postgres_schema(conn) == []
    finally:
        conn.close()
    store.initialize(settings.database).close()


@needs_postgres
def test_statements_that_used_to_be_sqlite_only_work_on_postgresql(settings):
    conn = store.initialize(settings.database)
    try:
        store.replace_tracker_selection(conn, [])  # NOT IN () is SQLite-only syntax
        first = store.start_sync_run(conn, now="2026-11-21T10:00:00+00:00")
        second = store.start_sync_run(conn, now="2026-11-21T11:00:00+00:00")
        assert second == first + 1  # RETURNING id instead of SQLite's lastrowid
        assert conn.execute("SELECT status FROM sync_runs WHERE id = ?", (first,)).fetchone()[0] == "failed"
        new, changed = store.upsert_discovered_apps(conn, [{"appid": 10, "name": "A", "last_modified": 1},
                                                           {"appid": 10, "name": "A2", "last_modified": 2}],
                                                    now="2026-11-21T11:00:00+00:00")
        assert (new, changed) == (1, 1)  # an app listed twice: new, then changed, as one at a time
        assert conn.execute("SELECT name, last_modified FROM discovered_apps").fetchall() == [("A2", 2)]
    finally:
        conn.close()


