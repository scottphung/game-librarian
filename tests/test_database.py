def test_placeholders_become_psycopgs_outside_literals_and_every_percent_sign_is_doubled():
    sql = "SELECT '50%', 'it''s ? here', \"odd?name\" FROM t -- a ? in a comment\nWHERE a = ? AND b LIKE ?"
    assert to_pyformat(sql) == ("SELECT '50%%', 'it''s ? here', \"odd?name\" FROM t -- a ? in a comment\n"
                                "WHERE a = %s AND b LIKE %s")


def test_a_row_reads_like_sqlite3s_row():
    row = Row({"appid": 0, "name": 1}, (570, "Dota 2"))
    assert row["appid"] == row[0] == 570 and row["name"] == "Dota 2"
    assert row.keys() == ["appid", "name"] and dict(row) == {"appid": 570, "name": "Dota 2"}
    assert tuple(row) == (570, "Dota 2") and len(row) == 2
    appid, name = row
    assert (appid, name) == (570, "Dota 2")
    with pytest.raises(IndexError):
        row["missing"]  # sqlite3.Row raises IndexError too


def test_the_postgresql_schema_is_sqlites_with_postgresqls_types():
    statements = postgres_statements(store.SCHEMA)
    joined = "\n".join(statements)
    assert "--" not in joined and "AUTOINCREMENT" not in joined and " REAL" not in joined
    assert "id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY" in joined
    assert 'name                   TEXT COLLATE "C",' in joined  # text sorts byte by byte, as in SQLite
    assert "appid                  BIGINT PRIMARY KEY" in joined
    assert "value          DOUBLE PRECISION NOT NULL" in joined
    tables = [statement for statement in statements if statement.startswith("CREATE TABLE")]
    assert len(tables) == len(store.schema_columns())


def test_every_table_is_known_with_its_columns_and_accounts_are_never_catalog_tables():
    columns = store.schema_columns()
    assert {"games", "accounts", "wishlist_items", "sales_estimates", "twitchtracker_summaries"} <= set(columns)
    assert list(columns).index("games") < list(columns).index("game_tags")  # parents first
    assert columns["wishlist_items"] == ("id", "account_id", "game_key", "name", "added_at")


